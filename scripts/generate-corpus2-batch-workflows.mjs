#!/usr/bin/env node
/**
 * Generates the 20 corpus-2 batch-solve GitHub Actions workflows (.github/workflows/
 * solver-corpus2-batch-NN.yml) plus their companion README. One-off infrastructure for a
 * rare/on-demand "fully refresh stress-corpus-2's solver benchmark data (badness/attempts/
 * stability telemetry for dev-benchmark curation) AND save any newly-found solves as real hints
 * with provenance, in one pass" task -- see .github/workflows/README-solver-corpus2-batches.md
 * for the full design rationale (why manual-dispatch-only, why a dedicated branch per batch, how
 * to combine results, how to delete these when done).
 *
 * Uses portfolio-solve-sweep.mjs --scheduler-mode=legacy --save-hints for the actual solving: it
 * calls the exact same Solver.solve() as scripts/stress/benchmark.mjs (confirmed: legacy mode
 * never also runs a portfolio-experiment comparison pass), and its buildRow() now records the
 * same attempts/badness/refereeValid telemetry stress:benchmark's report does (see
 * portfolio-solve-sweep-lib.mjs), so a batch's own --out file is ALREADY dev-benchmark-curation
 * compatible -- no separate stress:benchmark run needed. scripts/
 * portfolio-sweep-reports-to-benchmark.mjs combines the 20 batches' report files into one flat
 * report shaped like scripts/stress/benchmark.mjs's own output, for rank-levels.mjs/
 * classify-stability.mjs/curate-dev-benchmark.mjs to consume unmodified.
 *
 * Deliberately does NOT skip already-solved levels before starting: the goal is fresh telemetry
 * for every level in a batch's range, solved or not, not just closing hint-discovery gaps --
 * `--resume --checkpoint=<path>` alone (portfolio-solve-sweep.mjs's own incremental JSONL
 * checkpoint) already makes a batch resumable across separate workflow runs without needing a
 * separate "is this level already solved" pre-check.
 *
 * Regenerate after changing this file with:
 *   node scripts/generate-corpus2-batch-workflows.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const WORKFLOWS_DIR = path.join(ROOT, '.github', 'workflows');
const CORPUS_FILE = 'data/stress/stress-levels-random.json';
const TOTAL_LEVELS = 1700;
const BATCH_COUNT = 20;
const LEVELS_PER_BATCH = TOTAL_LEVELS / BATCH_COUNT; // 85, exact
if (!Number.isInteger(LEVELS_PER_BATCH)) throw new Error(`${TOTAL_LEVELS} does not divide evenly into ${BATCH_COUNT} batches`);

mkdirSync(WORKFLOWS_DIR, { recursive: true });

function pad2(n) { return String(n).padStart(2, '0'); }

function workflowYaml(batchNum) {
    const nn = pad2(batchNum);
    const start = (batchNum - 1) * LEVELS_PER_BATCH + 1;
    const end = batchNum * LEVELS_PER_BATCH;
    const branch = `stress-corpus2-batch-${nn}`;
    const logDir = `logs/solver-corpus2-batches`;
    const reportFile = `${logDir}/batch-${nn}.json`;
    const summaryFile = `${logDir}/batch-${nn}-summary.md`;
    const checkpointFile = `${logDir}/batch-${nn}.checkpoint.jsonl`;
    const consoleLogFile = `${logDir}/batch-${nn}.console.log`;

    return `# Generated by scripts/generate-corpus2-batch-workflows.mjs -- do not hand-edit.
# See .github/workflows/README-solver-corpus2-batches.md for what this is and how to use it.
# One-off, rare/on-demand infrastructure -- manual trigger only, not run on every push.
name: Solver corpus-2 batch ${batchNum}/${BATCH_COUNT} (levels ${start}-${end})

on:
  workflow_dispatch:
    inputs:
      budget_ms:
        description: 'Per-level solve budget in milliseconds'
        required: false
        default: '8000'
      # 20M, not 8M: the early repair probe's own fixed internal worst case is ~8-10M nodes
      # (REPAIR_PROBE_ORDINARY_NODE_BUDGET/_BIASED_NODE_BUDGET, orchestration.ts) -- at 8M a
      # repair-gated level that needs the full probe has nothing left over for the main
      # loop/fallback/attraction-diversity passes, silently defeating the point of the
      # 2026-07-17 repair-probe budget fixes (see CLAUDE.md's budget-composition gotcha).
      node_budget:
        description: 'Per-level node-count ceiling (deterministic backstop alongside budget_ms)'
        required: false
        default: '20000000'
      workers:
        description: 'Cross-level worker processes (GH-hosted ubuntu-latest runners have 2-4 cores)'
        required: false
        default: '2'

permissions:
  contents: write

concurrency:
  group: solver-corpus2-batch-${nn}
  cancel-in-progress: false

jobs:
  solve-batch-${nn}:
    name: Corpus-2 levels ${start}-${end}
    runs-on: ubuntu-latest
    timeout-minutes: 360
    steps:
      - name: Check out repository
        uses: actions/checkout@v4
        with:
          ref: main
          fetch-depth: 0

      - name: Check out the batch branch (continuing prior progress) or create it from main
        shell: bash
        run: |
          git fetch origin main
          if git ls-remote --exit-code --heads origin ${branch} >/dev/null 2>&1; then
            echo "Branch ${branch} already exists -- continuing from its current state."
            git fetch origin ${branch}
            git checkout -B ${branch} origin/${branch}
          else
            echo "Branch ${branch} does not exist yet -- creating from main."
            git checkout -B ${branch} origin/main
          fi

      - name: Setup Node
        uses: actions/setup-node@v4
        with:
          node-version: '20'
          cache: npm

      - name: Install dependencies
        run: npm ci

      - name: Prepare log files (always creates a valid result file before anything else runs)
        shell: bash
        run: |
          mkdir -p ${logDir}
          if [ ! -f ${reportFile} ]; then
            cat > ${reportFile} <<'JSON'
          {
           "summary": {
            "corpus": "${CORPUS_FILE}",
            "budgetMs": null,
            "status": "not-started"
           },
           "levels": [],
           "note": "placeholder written before the sweep ran; overwritten with real results as soon as the first level completes"
          }
          JSON
          fi
          touch ${consoleLogFile}
          echo "Prepared batch ${nn} (levels ${start}-${end}) at $(date -u +%FT%TZ)." | tee -a ${consoleLogFile}

      - name: Run portfolio-solve-sweep on this batch's levels (legacy scheduler only, matches production)
        id: sweep
        continue-on-error: true
        shell: bash
        run: |
          set +e
          timeout -k 30s --preserve-status 340m node scripts/run-bundled.mjs scripts/portfolio-solve-sweep.mjs \\
            --corpus=${CORPUS_FILE} \\
            --levels="${start}-${end}" \\
            --scheduler-mode=legacy \\
            --budget-ms="\${{ inputs.budget_ms }}" \\
            --node-budget="\${{ inputs.node_budget }}" \\
            --workers="\${{ inputs.workers }}" \\
            --resume --checkpoint=${checkpointFile} \\
            --save-hints \\
            --out=${reportFile} --summary-out=${summaryFile} \\
            2>&1 | tee -a ${consoleLogFile}
          status=\${PIPESTATUS[0]}
          echo "exit_code=\${status}" >> "$GITHUB_OUTPUT"
          exit 0

      - name: Commit and push whatever hints/results this run produced
        if: always()
        shell: bash
        run: |
          git config user.name 'github-actions[bot]'
          git config user.email 'github-actions[bot]@users.noreply.github.com'
          git add data/stress/hints-random/ ${CORPUS_FILE} ${logDir}/
          if git diff --cached --quiet; then
            echo "Nothing changed -- not creating an empty commit."
          else
            git commit -m "Batch ${nn}: corpus-2 levels ${start}-${end} solve progress"
            for attempt in 1 2 3 4; do
              if git push origin HEAD:${branch}; then break; fi
              echo "Push attempt \${attempt} failed; retrying after a short wait..."
              sleep $((attempt * 5))
              git fetch origin ${branch}
              if git rebase origin/${branch}; then continue; fi
              fallback_ref="refs/heads/${branch}-retry-\$(date +%s)"
              echo "Rebase failed -- pushing what we have to a fallback ref instead of losing it: \${fallback_ref}"
              git push origin "HEAD:\${fallback_ref}"
              break
            done
          fi

      - name: Upload batch logs as an artifact (belt and suspenders alongside the branch push)
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: solver-corpus2-batch-${nn}
          path: |
            ${reportFile}
            ${summaryFile}
            ${checkpointFile}
            ${consoleLogFile}
          if-no-files-found: warn
          retention-days: 30

      - name: Fail the job if the sweep itself failed (visibility only -- push/upload already happened above)
        if: always() && steps.sweep.outputs.exit_code != '0' && steps.sweep.outputs.exit_code != '124' && steps.sweep.outputs.exit_code != '143'
        run: |
          echo "sweep_exit_code=\${{ steps.sweep.outputs.exit_code }}"
          echo "Note: exit codes 124/143 (timeout/SIGTERM from the 340m wrapper) are treated as expected for a" \\
               "budget-exhausting batch, not a failure -- whatever was found before the timeout was already" \\
               "committed and pushed in the prior step."
          exit 1
`;
}

for (let batchNum = 1; batchNum <= BATCH_COUNT; batchNum++) {
    const filePath = path.join(WORKFLOWS_DIR, `solver-corpus2-batch-${pad2(batchNum)}.yml`);
    writeFileSync(filePath, workflowYaml(batchNum));
    console.log(`Wrote ${path.relative(ROOT, filePath)}`);
}
